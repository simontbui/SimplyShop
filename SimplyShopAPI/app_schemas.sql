CREATE TABLE stores (
    store_id integer GENERATED BY DEFAULT AS IDENTITY,
    store_name character varying(30) NOT NULL,
    store_name_display character varying(30) NOT NULL,
    street_address character varying(50) NOT NULL,
    city_address character varying(50) NOT NULL,
    state_address character varying(2) NOT NULL,
    zip_address character varying(6) NOT NULL,
    latitude double precision,
    longitude double precision,
    location geometry (point, 4326),
    date_created timestamp with time zone NOT NULL DEFAULT (now()),
    last_updated timestamp with time zone DEFAULT (now()),
    store_status_id integer NOT NULL,
