    last_updated timestamp with time zone DEFAULT (now()),
    CONSTRAINT "PK_products" PRIMARY KEY (product_id),
    CONSTRAINT products_brand_id_fkey FOREIGN KEY (brand_id) REFERENCES brands (brand_id) ON DELETE SET NULL,
    CONSTRAINT products_item_id_fkey FOREIGN KEY (item_id) REFERENCES items (item_id) ON DELETE RESTRICT,
    CONSTRAINT products_unit_type_id_fkey FOREIGN KEY (unit_type_id) REFERENCES unit_types (unit_type_id) ON DELETE RESTRICT
);

